function toDetail(seed: Seed): TenderDetail {
  const items = (seed.items ?? []).map(([description, quantity, unit, unitValue], index) => ({
    id: `${seed.id}-item-${index + 1}`,
    description,
    quantity,
    unit,
    estimatedUnitValue: unitValue,
    estimatedTotalValue: unitValue !== null && quantity !== null ? Math.round(unitValue * quantity * 100) / 100 : null,
  }));

  const documents = (seed.documents ?? []).map(([name, type, sizeBytes], index) => ({
    id: `${seed.id}-doc-${index + 1}`,
    name,
    type,
    sizeBytes,
    url: '#',
    publishedAt: seed.published,
  }));

  const timeline: TenderDetail['timeline'] = [{ at: seed.published, type: 'published', description: 'Edital publicado na fonte oficial.' }];
  if (seed.deadline) timeline.push({ at: seed.deadline, type: 'deadline_changed', description: 'Prazo final para envio de propostas.' });
  if (seed.status === 'suspended') timeline.push({ at: seed.published, type: 'status_changed', description: 'Processo suspenso pelo órgão.' });
  if (seed.status === 'cancelled') timeline.push({ at: seed.published, type: 'status_changed', description: 'Processo revogado.' });

  return {
    id: seed.id,
    title: seed.title,
    objectSummary: seed.description,
    organization: { id: seed.org[0], name: seed.org[1] },
    purchasingUnit: seed.unit,
    modality: seed.modality,
    modalityLabel: seed.modalityLabel,
    status: seed.status,
    tenderNumber: seed.number,
    estimatedValue: seed.value,
    publishedAt: seed.published,
    openingAt: seed.opening,
    proposalDeadline: seed.deadline,
    location: { state: seed.state, city: seed.city, cityIbgeCode: null },
    source: { id: seed.source[0], name: seed.source[1], url: seed.source[2] },
    categories: seed.categories.map((slug) => ({ slug, label: categoryLabels[slug] ?? slug })),
    relevance: { score: null, highlights: [] },
    updatedAt: seed.published,
    description: seed.description,
    processNumber: seed.process,
    items,
    documents,
    timeline,
    createdAt: seed.published,
  };
}

export const tenderFixtures: TenderDetail[] = seeds.map(toDetail);
